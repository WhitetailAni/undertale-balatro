SMODS.Joker {
	key = "flowery",
	config = {
		xmult = 1.5,
		all_flowers = false,
		orange_active = false,
		final_hand = false,
		udid = 0,
	},
	loc_vars = function(self, info_queue, card)
		if not card.debuff then
			self:play_flowery_sound_random({
				"flowery",
				"flowery2",
				"hey",
				"heyguys",
				"itsme",
				"itsmeflowery",
				"heytherelittleguy",
				"thisguysyourbestfriend",
				"glue",
			})
		end
		return { vars = { card.ability.xmult, localize("9", "ranks") or "9" } }
	end,
	add_to_deck = function(self, card, from_debuff)
		if not from_debuff then
			card.ability.udid = pseudorandom("flowery_udid")
			if #SMODS.find_card("j_UTDR_flowery") == 0 then
				G.GAME.flowery_udid = card.ability.udid
			end
		end
	
		self:last_jarona(card)
	end,
	rarity = 3,
	blueprint_compat = true,
	eternal_compat = true,
	atlas = "DR_jokers",
	pos = { x = 9, y = 9 },
	soul_pos = { x = 0, y = 12 },
	cost = 3,
	play_flowery_sound = function(self, sfx)
		if UTDR.config_file['voiceclips'] then
			play_sound("UTDR_flowery_"..sfx, 1.0, 0.7)
		end
	end,
	play_flowery_sound_random = function(self, table)
		if UTDR.config_file['voiceclips'] then
			local sfx = pseudorandom_element(table, "flowery_sfx")
			play_sound("UTDR_flowery_"..sfx, 1.0, 0.7)
		end
	end,
	is_card_flower = function(self, card, include_pink, include_flowery)
		if include_pink and card.config.center.key == "j_UTDR_pink" then
			return true
		end
		if include_flowery and card.config.center.key == "j_UTDR_flowery" then
			return true
		end
		return card.config.center.key == "j_UTDR_aqua" or card.config.center.key == "j_UTDR_seth" or card.config.center.key == "j_UTDR_yellow"or  card.config.center.key == "j_UTDR_blue" or card.config.center.key == "j_UTDR_green" or card.config.center.key == "j_UTDR_orange"
	end,
	last_jarona = function(self, card)
		local aquas = SMODS.find_card("j_UTDR_aqua")
		local seths = SMODS.find_card("j_UTDR_seth")
		local yellows = SMODS.find_card("j_UTDR_yellow")
		local blues = SMODS.find_card("j_UTDR_blue")
		local oranges = SMODS.find_card("j_UTDR_orange")
		local greens = SMODS.find_card("j_UTDR_green")
		local flowerys = SMODS.find_card("j_UTDR_flowery")
		local pinks = SMODS.find_card("j_UTDR_pink")

		if #aquas > 0 and #seths > 0 and #yellows > 0 and #blues > 0 and #oranges > 0 and #greens > 0 and not card.ability.all_flowers then
			self:play_flowery_sound("lend_me_your_power")
			card.ability.all_flowers = true

			for i = 1, #aquas do
				aquas[i]:set_eternal(true)
				aquas[i]:set_edition({ negative = true }, true)
			end
			for i = 1, #seths do
				seths[i]:set_eternal(true)
				seths[i]:set_edition({ negative = true }, true)
			end
			for i = 1, #yellows do
				yellows[i]:set_eternal(true)
				yellows[i]:set_edition({ negative = true }, true)
			end
			for i = 1, #blues do
				blues[i]:set_eternal(true)
				blues[i]:set_edition({ negative = true }, true)
			end
			for i = 1, #oranges do
				oranges[i]:set_eternal(true)
				oranges[i]:set_edition({ negative = true }, true)
				oranges[i].ability.all_flowers = true
			end
			for i = 1, #greens do
				greens[i]:set_eternal(true)
				greens[i]:set_edition({ negative = true }, true)
			end
			for i = 1, #flowerys do
				flowerys[i]:set_eternal(true)
				flowerys[i]:set_edition({ negative = true }, true)
			end
			--if you have her on the team, fun little bonus! not required for Last Jaronaing though
			for i = 1, #pinks do
				pinks[i]:set_eternal(true)
				pinks[i]:set_edition({ negative = true }, true)
			end
		end
	end,
	calculate = function(self, card, context)
		if context.repetition and context.cardarea == G.play then
			if context.other_card:get_id() == 9 then
				return {
					repetitions = 1,
				}
			end
		elseif context.individual and context.cardarea == G.play then
			if context.other_card:get_id() == 9 then
				return {
					xmult = card.ability.xmult,
				}
			end
		elseif (context.selling_card and self:is_card_flower(context.card, true, false)) or context.selling_self or (context.joker_type_destroyed and context.card.config.center.key == "j_UTDR_flowery") then
			if card.ability.udid == G.GAME.flowery_udid then
				local floweries = SMODS.find_card("j_UTDR_flowery")
				G.GAME.flowery_udid = floweries[#floweries].ability.udid
			end
			self:play_flowery_sound("goodbye")
		elseif card.ability.udid == G.GAME.flowery_udid and not context.blueprint then
			if context.showdown_blind_effect then
				self:play_flowery_sound("nonono")
			elseif context.after then
				card.ability.orange_active = false
			elseif context.before then
				self:last_jarona(card)
			elseif context.joker_main then
				local oranges = SMODS.find_card("j_UTDR_orange")
				local should_orange = false
				for i = 1, #oranges do
					if oranges[i].ability.card_was_sold then
						should_orange = true
					end
				end
				if G.GAME.current_round.hands_left == 0 then
					self:play_flowery_sound("last_jarona")
					card.ability.final_hand = true
				elseif card.ability.all_flowers then
					self:play_flowery_sound_random({
						"last_jarona",
						"lend_me_your_power",
						"omega_flowery"
					})
				else
					if should_orange and pseudorandom("ja_orange") > 0.67 then
						self:play_flowery_sound_random({
							"ja_orange_1",
							"ja_orange_2"
						})
					else
						self:play_flowery_sound_random({
							"blingo_blizzard",
							"flowers_blooms_in_your_heart",
							"wow",
							"try_my_flavor",
							"the_diner",
							"the_boys",
							"thatsgreat",
							"thats_my_dreams",
							"take_that",
							"suckle_it_up",
							"spiral_dance",
							"smile_again",
							"say_that_again",
							"prism_blow",
							"powering_up",
							"minipeppers",
							"leaf_it_to_me",
							"jarona1",
							"jarona2",
							"jarona3",
							"jarona4",
							"its_all_yours",
							"its_all_in_a_name",
							"im_only_trying_to_help_you",
							"huhillshowyou",
							"huh",
							"hoo",
							"hah",
							"glue",
							"give_it_to_you",
							"get_a_chance_1",
							"get_a_chance_2",
							"forget_it",
							"youre_a_hero",
							"glue",
						})
					end
				end
			elseif context.blind_defeated then
				if card.ability.final_hand and pseudorandom("its_my_jarona") > 0.67 then
					self:play_flowery_sound("heh_its_my_jarona")
					card.ability.final_hand = false
				else
					self:play_flowery_sound_random({
						"heh_one_more_for_the_fans",
						"heh_its_my_jarona",
						"according_to_plant",
						"wow",
						"thatsgreat",
						"leaf_it_to_me",
						"give_it_to_you",
					})
				end
			elseif context.game_over or context.skipping_booster then
				self:play_flowery_sound_random({
					"sustingus",
					"nonono",
					"goodbye",
					"go_home",
					"get_a_chance_1",
					"get_a_chance_2",
					"forget_it"
				})
