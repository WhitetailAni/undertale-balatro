function play_flowery_sound(sfx)
	if UTDR.config_file['voiceclips'] then
		play_sound("UTDR_flowery_"..sfx, 1.0, 0.7)
	end
end

function play_flowery_sound_random(table)
	if UTDR.config_file['voiceclips'] then
		local sfx = pseudorandom_element(table, "flowery_sfx")
		play_sound("UTDR_flowery_"..sfx, 1.0, 0.7)
	end
end

